_ACTION_DESCRIPTIONS_LOWER = {k.lower(): v for k, v in ACTION_DESCRIPTIONS.items()}
_DANGEROUS_LOWER = {k.lower(): (k, v) for k, v in DANGEROUS_PATTERNS.items()}


def get_service_name(prefix: str) -> str:
    key = prefix.lower()
    return SERVICE_NAMES.get(key, key.upper() if len(key) <= 4 else key.replace("-", " ").title())


def get_action_description(action: str) -> str | None:
    """Exact description for a known action (IAM action names are case-insensitive)."""
    return _ACTION_DESCRIPTIONS_LOWER.get(action.lower())


def get_dangerous_info(action: str) -> tuple[str, str] | None:
    """(severity, message) for a known dangerous action, matched case-insensitively."""
    entry = _DANGEROUS_LOWER.get(action.lower())
    return entry[1] if entry else None


def canonical_action_name(action: str) -> str:
    """Return the catalog's spelling of an action (e.g. 'IAM:passrole' -> 'iam:PassRole')."""
    lower = action.lower()
    if lower in _DANGEROUS_LOWER:
        return _DANGEROUS_LOWER[lower][0]
    for known in ACTION_DESCRIPTIONS:
        if known.lower() == lower:
            return known
    return action


def describe_action_by_pattern(action: str) -> tuple[str, str]:
    if ":" not in action:
        return ("unknown", action)

    prefix, action_name = action.split(":", 1)
    service = get_service_name(prefix)

    # API Gateway management actions are HTTP methods (apigateway:GET, apigateway:DELETE...)
    http_methods = {"GET": "read", "HEAD": "read", "OPTIONS": "read", "POST": "write", "PUT": "write",
                    "PATCH": "write", "DELETE": "delete"}
    if action_name.upper() in http_methods and action_name.isupper():
        return (http_methods[action_name], f"Send {action_name} requests to the {service} management API")

    for verb, category, template in ACTION_VERB_PATTERNS:
        rest = action_name[len(verb):]
        # Match whole verbs only: "Set" must not match "Setup", "Add" must not match "Address"
        if action_name.startswith(verb) and (not rest or rest[0].isupper() or rest[0] in "*?"):
            resource_type = _camel_to_words(rest.rstrip("*?")) if rest.rstrip("*?") else "resources"
            return (category, template.format(resource_type=resource_type, service=service))

    words = _camel_to_words(action_name)
    return ("other", f"{words[:1].upper()}{words[1:]} in {service}")


def _camel_to_words(name: str) -> str:
    if not name:
        return "resources"
    words = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1 \2', name)
    words = re.sub(r'([a-z])([A-Z])', r'\1 \2', words)
    return words.lower()
